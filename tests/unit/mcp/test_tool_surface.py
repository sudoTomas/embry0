def _json_type(prop: dict[str, Any]) -> str:
    if "type" in prop:
        return str(prop["type"])
    if "anyOf" in prop:
        return "|".join(_json_type(p) for p in prop["anyOf"])
    return "any"


async def _wire_tools() -> dict[str, dict[str, Any]]:
    """Each tool as ``tools/list`` serialises it (camelCase wire keys)."""
    tools = await server.mcp.list_tools()
    return {t.name: t.model_dump(by_alias=True, mode="json", exclude_none=True) for t in tools}


def _parameters(input_schema: dict[str, Any]) -> list[str]:
    required = set(input_schema.get("required", []))
    return sorted(
        f"{name}: {_json_type(prop)}" + ("" if name in required else f" = {json.dumps(prop.get('default'))}")
        for name, prop in input_schema.get("properties", {}).items()
    )


async def test_every_tool_keeps_its_parameters():
    tools = await _wire_tools()
    assert sorted(tools) == sorted(EXPECTED_PARAMETERS), "the set of tools changed"
    changed = {
        name: _parameters(tool["inputSchema"])
        for name, tool in tools.items()
        if _parameters(tool["inputSchema"]) != EXPECTED_PARAMETERS[name]
    }
    assert changed == {}, f"tool parameters changed (now): {changed}"


async def test_every_tool_is_described_by_its_docstring():
    """The description is what the model routes on; the registration must not lose it."""
    tools = await _wire_tools()
    for name, tool in tools.items():
        doc = getattr(server, name).__doc__
        assert doc, f"{name} has no docstring"
        assert tool.get("description") == doc, f"{name}'s description is not its docstring"


async def test_every_confirm_gated_tool_defaults_to_refusing():
    """The destructive-tool pattern lives in the schema: confirm is optional and false."""
    tools = await _wire_tools()
    gated = {name for name, tool in tools.items() if "confirm" in tool["inputSchema"].get("properties", {})}
    assert gated == {
        "agent_reset",
        "agent_update",
        "case_accept",
        "case_close",
        "credential_bind",
        "env_delete",
        "env_set",
        "host_import_tailnet",
        "job_answer",
        "job_cancel",
        "job_resume",
        "merge_decide",
        "org_register",
        "org_webhook_install",
        "qa_config_set",
        "repo_register",
    }
    for name in gated:
        confirm = tools[name]["inputSchema"]["properties"]["confirm"]
        assert (confirm.get("type"), confirm.get("default")) == ("boolean", False), name
        assert "confirm" not in tools[name]["inputSchema"].get("required", []), name
