/** A "#rrggbb" colour 18% of the way to white; any other colour (a CSS variable) as it is. */
export function lift(color: string): string {
  const m = /^#([0-9a-f]{2})([0-9a-f]{2})([0-9a-f]{2})$/i.exec(color);
  if (!m) return color;
  const channel = (hex: string) => Math.round(parseInt(hex, 16) * 0.82 + 255 * 0.18).toString(16).padStart(2, "0");
  return `#${channel(m[1])}${channel(m[2])}${channel(m[3])}`;
}
