/**
 * The roster (spec 3.2): twelve avatars as 16x16 character grids, one
 * Record<SpriteState, Frame[]> each, compiled once at module load into one
 * SVG path per character class so a rendered frame is at most four paths.
 * Not part of the divine layer (divine/CLAUDE.md rule 9): sprites may sit on
 * live cards and lists, step no faster than two frames per second, and the
 * source of this file stays under 40 KB (sprites.test.ts).
 *
 * Each avatar draws four frames by hand (idle, tool, done, failed); the other
 * five follow the state rules mechanically (figure below), which keeps all
 * 108 frames inside the budget and the rules true by construction.
 */

export type SpriteState = "idle" | "thinking" | "tool" | "done" | "failed" | "pending";
export type CharClass = "o" | "f" | "h" | "e";
export type Frame = readonly string[];
export type CompiledFrame = Partial<Record<CharClass, string>>;

export const SPRITE_STATES: readonly SpriteState[] = ["idle", "thinking", "tool", "done", "failed", "pending"];
export const FRAME_COUNTS: Record<SpriteState, 1 | 2> = { idle: 2, thinking: 2, tool: 2, done: 1, failed: 1, pending: 1 };

/** Run-length rectangles, one path per class: "M<x> <y>h<len>v1h-<len>z" per run. */
export function compileFrame(frame: Frame): CompiledFrame {
  const out: Partial<Record<CharClass, string[]>> = {};
  frame.forEach((row, y) => {
    let x = 0;
    while (x < 16) {
      const c = row[x];
      if (c === ".") { x++; continue; }
      let len = 1;
      while (x + len < 16 && row[x + len] === c) len++;
      (out[c as CharClass] ??= []).push(`M${x} ${y}h${len}v1h-${len}z`);
      x += len;
    }
  });
  const paths: CompiledFrame = {};
  for (const k of Object.keys(out) as CharClass[]) paths[k] = out[k]!.join("");
  return paths;
}

const BLANK = ".".repeat(16);

/** The frames drawn by hand. idle leaves row 0 empty for the bob and the spark. */
interface Drawn { idle: Frame; tool: Frame; done: Frame; failed: Frame }

/** idle frame 1: frame 0 shifted up one row. */
function bob(frame: Frame): Frame {
  return [...frame.slice(1), BLANK];
}

/** thinking: a one-cell highlight above the head at column x, eyes closed when asked. */
function spark(frame: Frame, x: number, eyesClosed: boolean): Frame {
  const rows = eyesClosed ? frame.map((r) => r.replace(/e/g, "f")) : [...frame];
  rows[0] = rows[0].slice(0, x) + "h" + rows[0].slice(x + 1);
  return rows;
}

/** pending: the outline alone. */
function ghost(frame: Frame): Frame {
  return frame.map((r) => r.replace(/[fhe]/g, "."));
}

/** All six states from the drawn frames; sparkAt is the spark's column on thinking frame 0. */
function figure(sparkAt: number, d: Drawn): Record<SpriteState, Frame[]> {
  return {
    idle: [d.idle, bob(d.idle)],
    thinking: [spark(d.idle, sparkAt, true), spark(d.idle, sparkAt + 1, false)],
    tool: [d.tool, d.idle],
    done: [d.done],
    failed: [d.failed],
    pending: [ghost(d.idle)],
  };
}

